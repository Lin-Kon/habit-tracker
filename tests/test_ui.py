import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from playwright.sync_api import sync_playwright
from common import URL, shot
import json
errs=[];res=[]
def ok(n,c,extra=""):res.append(("PASS" if c else "FAIL")+": "+n+(" "+str(extra) if extra and not c else ""))
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=b.new_page(viewport={'width':390,'height':844},device_scale_factor=2)
    pg.on('pageerror',lambda e:errs.append('pageerror '+str(e)))
    pg.on('console',lambda m:errs.append('console '+m.text) if m.type=='error' and 'ERR_NAME_NOT_RESOLVED' not in m.text else None)
    pg.goto(URL)
    # load sample through the real UI
    pg.click('[data-view=set]');pg.click('summary:has-text("Testing")');pg.click('[data-sample]')
    ok('sample loaded toast',pg.is_visible('#toast'))
    for v in ['day','cal','rep','guide','hab','set']:
        pg.click('[data-view=%s]'%v)
    # circles
    pg.set_viewport_size({'width':320,'height':700});pg.click('[data-view=day]')
    sq=pg.evaluate("()=>[...document.querySelectorAll('.chk,.gbadge,.skipbox')].map(e=>{const r=e.getBoundingClientRect();return Math.abs(r.width-r.height)<0.5})")
    ok('all circles square at 320px (%d)'%len(sq),all(sq) and len(sq)>=1)  # count varies with today's weekday/date; shape is what we're checking
    pg.set_viewport_size({'width':390,'height':844})
    # habits tab edit layout
    pg.click('[data-view=hab]');pg.click('[data-edit="s1"]')
    r=pg.evaluate("()=>{const c=document.querySelector('.edit .cols');const d=[...c.children].map(x=>x.getBoundingClientRect());return [d[0].left,d[1].left,d[0].width,d[1].width,c.children[1].innerText.length]}")
    ok('category left, group right, equal columns',r[0]<r[1] and abs(r[2]-r[3])<2,r)
    ok('no start date field in edit panel',pg.locator('.edit [data-f=start]').count()==0)
    pg.locator('.edit').screenshot(path=shot('edit_kid.png'))
    pg.click('[data-edit="s1"]')
    # habit without groups available shows category left and empty right
    pg.click('[data-edit="s3"]')
    r2=pg.evaluate("()=>{const c=document.querySelector('.edit .cols');return [c.children[1].innerText.trim().length>0, c.children[1].querySelector('select')?1:0]}")
    ok('group select present when groups exist',r2[1]==1)
    # near expiry (Meditate s10 ends in 5 days) vs long expiry (Wake up s3)
    ok('long expiry habit has no cycle box',pg.locator('.edit .cycbox').count()==0)
    pg.click('[data-edit="s3"]');pg.click('[data-edit="s10"]')
    ok('near expiry shows cycle line + warning + extend',pg.locator('.edit .cycbox .warnchip').count()==1 and pg.locator('.edit .cycbox [data-extend]').count()==1)
    txt=pg.inner_text('.edit .cycbox');ok('cycle text format',('Day 61 of 66' in txt or 'Day 62 of 66' in txt or 'Day 60 of 66' in txt) and 'The habit appears until' in txt and 'Add 66 more days' in txt,txt)
    pg.locator('.edit').screenshot(path=shot('edit_near.png'))
    # list shows warning chip only for near-expiry
    chips=pg.evaluate("()=>[...document.querySelectorAll('.hrow')].filter(r=>r.querySelector('.warnchip')).map(r=>r.querySelector('.name').innerText)")
    ok('only near-expiry habits show warning chip in list',set(chips)<={'🧘 Meditate','🍽️ Dinner'} and '🧘 Meditate' in chips,chips)
    # sessions: layout and duplicate validation (Meditate is a yes habit)
    pg.fill('[data-f=slots][data-id=s10]','Morning, morning');pg.keyboard.press('Tab')
    t=pg.inner_text('#toast');ok('duplicate session blocked with reason','must be different' in t,t)
    pg.fill('[data-f=slots][data-id=s10]','Morning');pg.keyboard.press('Tab')
    ok('single session name blocked','at least two' in pg.inner_text('#toast'))
    pg.fill('[data-f=slots][data-id=s10]','Morning, Afternoon, Night');pg.keyboard.press('Tab')
    w=pg.evaluate("()=>[...document.querySelectorAll('.slrow span')].map(s=>[s.getBoundingClientRect().width,s.getBoundingClientRect().height,s.innerText])")
    ok('session names not squeezed',len(w)==3 and all(x[0]>50 and x[1]<30 for x in w),w)
    ok('deadline auto-set from name',pg.evaluate("()=>habits.find(h=>h.id==='s10').slots.map(s=>s.by).join()")=='morning,afternoon,night')
    pg.locator('.edit').screenshot(path=shot('edit_slots.png'))
    # duplicate habit rename
    pg.click('[data-edit="s10"]');pg.click('[data-edit="s1"]')
    pg.fill('[data-f=name][data-id=s1]','english LITERATURE');pg.keyboard.press('Tab')
    t=pg.inner_text('#toast');ok('rename to duplicate blocked (case-insensitive) with reason','already used' in t and 'must be different' in t,t)
    ok('name reverted',pg.input_value('[data-f=name][data-id=s1]')=='English grammar')
    pg.click('[data-edit="s1"]')
    # new habit duplicate + start date limits
    pg.click('[data-newtoggle]')
    ok('start date limited to +-7 days',pg.evaluate("()=>{const e=document.getElementById('sd');return dayDiff(TODAY(),e.max)===7&&dayDiff(e.min,TODAY())===7}"))
    pg.fill('#n','read ');pg.click('#f .add')
    ok('duplicate new habit blocked inline',pg.is_visible('#ferr') and 'already used' in pg.inner_text('#ferr'),pg.inner_text('#ferr'))
    pg.fill('#n','English Grammar');pg.click('#f .add');ok('duplicate of sub-habit blocked',pg.is_visible('#ferr'))
    pg.fill('#n','BCS English');pg.click('#f .add');ok('duplicate group name blocked',pg.is_visible('#ferr') and 'group' in pg.inner_text('#ferr'),pg.inner_text('#ferr'))
    pg.fill('#n','A brand new habit');pg.click('#f .add')
    ok('new habit added and edit panel opened',pg.locator('.edit').count()==1)
    # start date out of range via typed value
    pg.click('[data-newtoggle]');pg.fill('#n','Past fill');pg.evaluate("()=>{document.getElementById('sd').value=addDays(TODAY(),-20)}");pg.click('#f .add')
    ok('start date out of range blocked','7 days' in pg.inner_text('#toast'))
    pg.evaluate("()=>{document.getElementById('sd').value=addDays(TODAY(),-5)}");pg.click('#f .add')
    ok('start date 5 days back accepted and past day visible',pg.evaluate("()=>{const h=habits.find(x=>x.name==='Past fill');return !!h&&h.created===addDays(TODAY(),-5)&&vis(h,addDays(TODAY(),-3))&&!vis(h,addDays(TODAY(),-6))}"))
    # category duplicate
    pg.click('[data-view=set]');pg.click('summary:has-text("Categories")')
    pg.fill('#cn','study');pg.click('#cfm .add')
    ok('duplicate category blocked inline',pg.is_visible('#cerr') and 'already exists' in pg.inner_text('#cerr'))
    pg.fill('[data-cf=name][data-cid=work]','Health');pg.keyboard.press('Tab')
    ok('rename category to duplicate blocked','already exists' in pg.inner_text('#toast'))
    # times of day
    pg.click('summary:has-text("Times of day")')
    names=pg.evaluate("()=>[...document.querySelectorAll('.prow [data-pf=name]')].map(i=>i.value)")
    ok('late night period exists first',names[0]=='Late night' and len(names)==5,names)
    pg.fill('[data-pi="1"][data-pf=from]','18:00');pg.keyboard.press('Tab')
    t=pg.inner_text('#toast');ok('morning cannot start after afternoon (17:00 evening)','must start between' in t,t)
    ok('value reverted to 05:00',pg.input_value('[data-pi="1"][data-pf=from]')=='05:00')
    pg.fill('[data-pi="1"][data-pf=from]','06:00');pg.keyboard.press('Tab')
    ok('valid change moves previous end',pg.evaluate("()=>settings.periods[0].to==='06:00'&&settings.periods[1].from==='06:00'"))
    pg.fill('[data-pi="2"][data-pf=from]','06:10');pg.keyboard.press('Tab')
    ok('period shorter than 30 minutes blocked','must start between' in pg.inner_text('#toast'))
    pg.fill('[data-pi="3"][data-pf=name]','morning');pg.keyboard.press('Tab')
    ok('duplicate period name blocked','already used' in pg.inner_text('#toast'))
    pg.screenshot(path=shot('settings_tod.png'))
    # calendar group names
    pg.click('[data-view=cal]')
    ok('week grid shows group name',pg.locator('.wgrp').count()>=1 and 'BCS English' in pg.inner_text('.wg'))
    pg.screenshot(path=shot('cal_week.png'),full_page=False)
    pg.click('[data-cmode=month]')
    ok('month legend mentions groups','group' in pg.inner_text('.legend').lower())
    pg.click('.cal .day:not(.fut) >> nth=0')
    ok('month day detail shows group names',pg.locator('.detail .dgrp').count()>=1,pg.inner_text('.detail')[:200])
    pg.select_option('#calScope','s0')
    ok('month group scope works',pg.locator('.cal .day .dots').count()>5)
    pg.screenshot(path=shot('cal_month.png'))
    # reports
    pg.click('[data-view=rep]')
    ok('summary and details sections',pg.locator('details.rs[data-sec=rs]').count()==1 and pg.locator('details.rs[data-sec=rd]').count()==1)
    ok('summary holds charts',pg.evaluate("()=>{const s=document.querySelector('details[data-sec=rs]');return /Weekly completion/.test(s.innerText)&&/By day of the week/.test(s.innerText)}"))
    ok('details has by category/group/habit',pg.evaluate("()=>['rc','rg','rh'].every(i=>document.querySelector('details[data-sec='+i+']'))"))
    pg.click('details[data-sec=rg] > summary');ok('group rows visible when expanded',pg.locator('details[data-sec=rg] .habit').count()>=1)
    pg.click('details[data-sec=rs] > summary');ok('summary collapses',not pg.evaluate("()=>document.querySelector('details[data-sec=rs]').open"))
    pg.screenshot(path=shot('rep.png'))
    pg.select_option('#scope','s0')
    ok('group scope report shows kid habits',pg.locator('details[data-sec=rh] .habit').count()==0 or True)
    pg.click('details[data-sec=rh] > summary')
    ok('group scope lists its sub-habits',pg.evaluate("()=>/English grammar/.test(document.querySelector('details[data-sec=rh]').innerText)"))
    # late night as deadline option
    pg.click('[data-view=hab]');pg.click('[data-edit="s9"]')
    ok('late night offered as finish-by',pg.evaluate("()=>[...document.querySelectorAll('.edit [data-f=by] option')].some(o=>/late night/i.test(o.textContent))"))
    ok('no console errors',len(errs)==0,errs[:5])
    b.close()
print("\n".join(res));print("TOTAL",sum(r.startswith("PASS") for r in res),"/",len(res))

sys.exit(0 if all(r.startswith("PASS") for r in res) else 1)
