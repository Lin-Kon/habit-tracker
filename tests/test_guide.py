import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from playwright.sync_api import sync_playwright
from common import URL, shot
errs=[];res=[]
def ok(n,c,extra=""):res.append(("PASS" if c else "FAIL")+": "+n+(" "+str(extra) if (extra and not c) else ""))
URL=URL
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2);pg=ctx.new_page()
    pg.on('pageerror',lambda e:errs.append('pageerror '+str(e)))
    pg.on('console',lambda m:errs.append('console '+m.text) if m.type=='error' and 'ERR_NAME_NOT_RESOLVED' not in m.text else None)
    pg.goto(URL)
    # ---- 1. unpersonalised user
    ok('first-run prompt visible',pg.is_visible('text=Want guidance that fits your life?'))
    ok('no coach card or rough-day button before questionnaire',pg.locator('.coach').count()==0 and pg.locator('[data-rough]').count()==0)
    pg.click('[data-pdismiss]');pg.reload()
    ok('dismissed prompt stays dismissed',not pg.is_visible('text=Want guidance that fits your life?'))
    pg.click('[data-view=guide]')
    ok('guide intro and badges for no profile',pg.is_visible('text=Guidance that fits your life') and pg.locator('.lvl').count()==1)
    # ---- 2. questionnaire
    pg.click('.gcard [data-obstart]')
    ok('welcome step with privacy and disclaimer','stays on this device' in pg.inner_text('.gcard') and 'not a doctor' in pg.inner_text('.gcard'))
    pg.click('[data-obnext]')
    pg.fill('#obn','Alex');pg.click('[data-obset=age][data-v="23-29"]');ok('age chip pressed',pg.get_attribute('[data-obset=age][data-v="23-29"]','aria-pressed')=='true')
    ok('name kept after chip click',pg.input_value('#obn')=='Alex')
    pg.click('[data-obnext]');pg.click('[data-obset=role][data-v=grad]');pg.click('[data-obnext]')
    for f in ['career','skills','move','body','fun']:pg.click('[data-obfocus=%s]'%f)
    pg.click('[data-obfocus=food]');pg.click('[data-obfocus=money]')
    ok('focus limited to five with message',pg.is_visible('#toast') and 'up to five' in pg.inner_text('#toast'))
    pg.click('[data-obfocus=fun]');pg.click('[data-obfocus=fun]')
    ok('focus keeps order and count',pg.evaluate("()=>ob.a.focus.join()")=='career,skills,move,body,fun',pg.evaluate("()=>ob.a.focus.join()"))
    pg.click('[data-obnext]');pg.click('[data-obnext]')  # skip optional step
    pg.click('[data-obset=tone][data-v=warm]');pg.click('[data-obnext]')
    sm=pg.inner_text('.gcard');ok('summary lists answers','Alex' in sm and '23' in sm and 'looking for work' in sm and 'not shared' in sm,sm[:200])
    pg.click('[data-obfinish]')
    prof=pg.evaluate("()=>settings.profile")
    ok('profile saved',prof['name']=='Alex' and prof['age']=='23-29' and prof['role']=='grad' and prof['tone']=='warm' and prof['focus']==['career','skills','move','body','fun'],prof)
    ok('lands on My plan',pg.evaluate("()=>guideTab")=='plan')
    ids=pg.evaluate("()=>buildPlan(settings.profile).map(s=>s.id)")
    ok('job-seeking steps for a graduate',all(x in ids for x in ['c_apply','c_int','c_net','c_cv']),ids)
    ok('age-appropriate exercise: jogging, no teen play',('m_jog' in ids) and ('m_play' not in ids) and ('m_play2' not in ids),ids)
    ok('eye, skin and face care offered',all(x in ids for x in ['b_eye','b_skin','b_face']),ids)
    ok('gaming offered with balance note',('fu_game' in ids) and 'keep it a choice' in pg.inner_text('#view'))
    ok('no diet note when eating was not chosen','diet plan' not in pg.inner_text('#view'))
    pg.screenshot(path=shot('plan.png'))
    # ---- 3. add steps
    pg.click('[data-stepadd=c_apply]')
    h=pg.evaluate("()=>{const h=habits.find(x=>x.step==='c_apply');return h&&[h.name,h.tiny,h.freq.t,!!h.desc,h.cat]}")
    ok('adding a step creates a habit with small step and explanation',h and h[1]==1 and h[2]=='weekdays' and h[3]==True,h)
    ok('added step shows as in your habits',pg.locator('.step:has-text("Send applications") .warnchip').count()==1)
    n0=pg.evaluate("()=>habits.length");pg.click('[data-stepall]');n1=pg.evaluate("()=>habits.length")
    ok('add all adds the rest once',n1>n0+8 and pg.evaluate("()=>new Set(habits.map(h=>h.name.toLowerCase())).size===habits.length"),(n0,n1))
    ok('skin care created with two sessions',pg.evaluate("()=>{const h=habits.find(x=>x.step==='b_skin');return h&&hasSlots(h)&&h.slots.length===2}"))
    ok('add-all button disappears once everything is added',pg.locator('[data-stepall]').count()==0)
    pg.click('[data-stepskip=fu_free]') if pg.locator('[data-stepskip=fu_free]').count() else None
    # ---- 4. coach card, tiny chip, praise
    pg.click('[data-view=day]')
    ok('coach note greets by name','Alex' in pg.inner_text('.coach'),pg.inner_text('.coach'))
    ok('rough day button now available',pg.locator('[data-rough]').count()==1)
    pg.evaluate("()=>{habits.push({id:'w1',name:'Walk test',type:'num',unit:'minutes',target:30,tiny:5,cat:'health',created:TODAY(),cycles:1,done:{},notes:{},freq:{t:'daily'},color:'#2f9e6e'});render()}")
    ok('small step chip shown',pg.locator('[data-tiny=w1]').count()==1)
    pg.click('[data-tiny=w1]')
    st=pg.evaluate("()=>{const h=habits.find(x=>x.id==='w1');return [dayVal(h,TODAY()),isDone(h,TODAY()),isFull(h,TODAY()),isSmall(h,TODAY())]}")
    ok('small step logs value, counts as done but not full',st==[5,True,False,True],st)
    ok('encouraging message after a small step',pg.is_visible('#toast') and len(pg.inner_text('#toast'))>10,pg.inner_text('#toast'))
    ok('row says small step counted','small step counted' in pg.inner_text('.habit:has(input[data-id=w1])'))
    pg.evaluate("()=>{const h=habits.find(x=>x.id==='w1');setVal(h,TODAY(),null,30);render()}")
    ok('full goal is full',pg.evaluate("()=>isFull(habits.find(x=>x.id==='w1'),TODAY())"))
    pg.evaluate("()=>{const h=habits.find(x=>x.id==='w1');setVal(h,TODAY(),null,5);render()}")
    # edit panel: tiny field and validation
    pg.click('[data-view=hab]');pg.evaluate("()=>{settings.hcollapsed={};save();render()}");pg.click('[data-edit=w1]')
    ok('small step field in edit panel',pg.locator('[data-f=tiny][data-id=w1]').count()==1)
    pg.fill('[data-f=tiny][data-id=w1]','40');pg.keyboard.press('Tab')
    ok('small step must be below goal and old value kept',pg.evaluate("()=>habits.find(x=>x.id==='w1').tiny")==5 and 'smaller than your goal' in pg.inner_text('#toast'),pg.inner_text('#toast'))
    pg.click('[data-edit=w1]')
    # reports small steps
    pg.click('[data-view=rep]')
    ok('reports show small steps counted','Small steps counted' in pg.inner_text('details[data-sec=rs]'))
    # ---- 5. rough day
    pg.click('[data-view=day]');pg.click('[data-rough]')
    ok('rough day panel with two kind options',pg.locator('[data-roughon]').count()==1 and pg.locator('[data-rest]').count()==1)
    due0=pg.evaluate("()=>act().filter(h=>h.type!=='group'&&!isWeekly(h)&&vis(h,TODAY())&&isDue(h,TODAY())&&!isDone(h,TODAY())).length")
    pg.click('[data-rest]')
    sk=pg.evaluate("()=>act().filter(h=>skipped(h,TODAY())).length")
    ok('rest day skips scheduled undone habits',sk==due0 and sk>0,(sk,due0))
    ok('rest day message',('rest day' in pg.inner_text('.coach').lower()))
    pg.click('[data-restundo]')
    ok('undo rest removes skips',pg.evaluate("()=>act().filter(h=>skipped(h,TODAY())).length")==0 and not pg.evaluate("()=>settings.rough[TODAY()]"))
    pg.click('[data-rough]');pg.click('[data-roughon]')
    ok('small steps only mode shows rough message and hides behind banner',pg.locator('.coach.rough').count()==1 and pg.inner_text('#behindbar').strip()=='')
    pg.click('[data-roughoff]');ok('rough mode off',pg.locator('.coach.rough').count()==0)
    # ---- 6. this week and reflection
    pg.click('[data-view=guide]');pg.click('[data-gtab=week]')
    ok('weekly letter addresses the user and is kind','Dear Alex' in pg.inner_text('.letter') and 'proud' in pg.inner_text('.letter'),pg.inner_text('.letter')[:200])
    pg.fill('[data-refl]','Walked every day');pg.keyboard.press('Tab')
    ok('reflection saved',pg.evaluate("()=>Object.values(settings.reflections).includes('Walked every day')"))
    pg.click('[data-gtab=today]')
    ok('today tab: small step, phase and thought','Your one small step today' in pg.inner_text('#view') and 'looking for work' in pg.inner_text('#view') and 'A thought for today' in pg.inner_text('#view'))
    pg.click('[data-gtab=badges]');ok('badges still reachable',pg.locator('.lvl').count()==1)
    # ---- 7. tone and privacy settings
    pg.click('[data-view=set]');pg.click('summary:has-text("Coach and privacy")')
    ok('privacy note shown','only in this browser' in pg.inner_text('details[data-sec=coach]'))
    pg.select_option('#tonesel','steady')
    pg.click('[data-view=day]')
    ok('tone changes the voice','Alex' in pg.inner_text('.coach') and pg.evaluate("()=>settings.profile.tone")=='steady')
    pg.click('[data-view=set]');pg.click('[data-coachtoggle]');pg.click('[data-view=day]')
    ok('coach notes can be turned off',pg.locator('.coach').count()==0 and pg.locator('[data-rough]').count()==0)
    pg.click('[data-view=set]');pg.click('[data-coachtoggle]')
    pg.click('[data-profreset]');ok('profile removed',pg.evaluate("()=>settings.profile")is None)
    pg.click('[data-undo]');ok('undo restores profile',pg.evaluate("()=>!!settings.profile&&settings.profile.name")=='Alex')
    # ---- 8. plan variants (logic)
    v=pg.evaluate("""()=>{const q=(p)=>buildPlan(p).map(s=>s.id);
      return {teen:q({age:'u18',role:'school',focus:['move','sleep','study']}),mid:q({age:'45-59',role:'work',focus:['move','career']}),old:q({age:'60+',role:'pause',focus:['move','sleep']}),
      parent:q({age:'30-44',role:'home',kids:'young',focus:['family','move']}),nokids:q({age:'30-44',role:'work',kids:'none',focus:['family']}),food:q({age:'23-29',role:'grad',focus:['food']}),none:q({age:'23-29',role:'grad',focus:[]})}}""")
    ok('teen: play, early bedtime, study',('m_play' in v['teen']) and ('s_bed_u' in v['teen']) and ('st_focus' in v['teen']),v['teen'])
    ok('45-59: brisk walk, not jogging',('m_walk2' in v['mid']) and ('m_jog' not in v['mid']),v['mid'])
    ok('60+: balance practice and later bedtime',('m_balance' in v['old']) and ('s_bed_o' in v['old']),v['old'])
    ok('parent of young children: child time and me time',('fa_kid' in v['parent']) and ('fa_me' in v['parent']),v['parent'])
    ok('no children: no parenting-with-child step',('fa_kid' not in v['nokids']),v['nokids'])
    ok('food steps are gentle habits not calorie targets',all(not any(w in (s['why']+s['name']).lower() for w in ['calorie','kcal','weight loss','lose weight']) for s in pg.evaluate("()=>STEPS.filter(s=>s.area==='food')")))
    ok('empty focus falls back to movement, sleep, calm',len(v['none'])>0)
    # ---- 9. sample data with profile
    ctx2=b.new_context(viewport={'width':390,'height':844});pg2=ctx2.new_page();pg2.goto(URL)
    pg2.click('[data-view=set]');pg2.click('summary:has-text("Testing")');pg2.click('[data-sample]')
    ok('sample loads a profile so Guide can be explored',pg2.evaluate("()=>!!settings.profile"))
    for v_ in ['day','cal','rep','guide','hab','set']:pg2.click('[data-view=%s]'%v_)
    pg2.click('[data-view=guide]')
    for g in ['plan','week','today','badges']:pg2.click('[data-gtab=%s]'%g)
    pg2.click('[data-view=day]');pg2.screenshot(path=shot('log_coach.png'))
    ok('no console errors',len(errs)==0,errs[:4])
    b.close()
print("\n".join(res));print("TOTAL",sum(r.startswith("PASS") for r in res),"/",len(res))

sys.exit(0 if all(r.startswith("PASS") for r in res) else 1)
